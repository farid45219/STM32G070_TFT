void TFT_GPIO_Init(void)
{
	RCC->IOPENR  |=  RCC_IOPENR_GPIOAEN;
	//RS pin, in HW silk it's GDO1, but in schematic GDO0
	GPIOA->MODER &=~ GPIO_MODER_MODE11_Msk;
	GPIOA->MODER |= (1 << GPIO_MODER_MODE11_Pos);
	
	//RESET pin, in HW silk it's GDO3, but in schematic GDO2
	GPIOA->MODER &=~ GPIO_MODER_MODE12_Msk;
	GPIOA->MODER |= (1 << GPIO_MODER_MODE12_Pos);
}

void TFT_RS_Pin_State_Set(uint8_t state)
{
	if(state == LOGIC_HIGH)
	{
		GPIOA->BSRR = GPIO_BSRR_BS11;
	}
	else
	{
		GPIOA->BSRR = GPIO_BSRR_BR11;
	}
}

void TFT_Reset_Pin_State_Set(uint8_t state)
{
	if(state == LOGIC_HIGH)
	{
		GPIOA->BSRR = GPIO_BSRR_BS12;
	}
	else
	{
		GPIOA->BSRR = GPIO_BSRR_BR12;
	}
}

void TFT_Write_Cmd(uint8_t cmd)
{
	GPIOA->BSRR = GPIO_BSRR_BR11;
	SPI_Slave_Select();
	SPI_Transfer(cmd);
	SPI_Slave_Deselect();
}

void TFT_Write_Data(uint8_t data)
{
	GPIOA->BSRR = GPIO_BSRR_BS11;
	SPI_Slave_Select();
	SPI_Transfer(data);
	SPI_Slave_Deselect();
}

