void TFT_Fill_Rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
	uint8_t  hi, lo;
    uint16_t x1 = x + TFT_X_OFFSET;
    uint16_t y1 = y + TFT_Y_OFFSET;
    uint16_t x2 = x1 + w - 1;
    uint16_t y2 = y1 + h - 1;

    //set coloumn address (XS to XE)
    TFT_Write_Cmd(0x2A);
    TFT_Write_Data(x1 >> 8);
    TFT_Write_Data(x1 & 0xFF);
    TFT_Write_Data(x2 >> 8);
    TFT_Write_Data(x2 & 0xFF);
	
	//set row address (YS to YE)
    TFT_Write_Cmd(0x2B);
    TFT_Write_Data(y1 >> 8);
    TFT_Write_Data(y1 & 0xFF);
    TFT_Write_Data(y2 >> 8);
    TFT_Write_Data(y2 & 0xFF);
	
	//memory write command
    TFT_Write_Cmd(0x2C);
	
	TFT_RS_Pin_State_Set(LOGIC_HIGH);
	SPI_Slave_Select();
	
	hi = color >> 8;
    lo = color & 0xFF;
	
    //Send the buffer line-by-line
    for (uint16_t j = 0; j < h; j++)
    {
        for (uint16_t i = 0; i < w; i++)
        {
            SPI_Transfer(hi);
            SPI_Transfer(lo);
        }
    }
	SPI_Slave_Deselect();
}

void TFT_Print_Number(uint8_t num, uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
	uint8_t  hi, lo, char_val = 1;
	uint16_t bytes, len, offset, end;
	int16_t  bits;
    uint16_t x1 = x + TFT_X_OFFSET;
    uint16_t y1 = y + TFT_Y_OFFSET;
    uint16_t x2 = x1 + w - 1;
    uint16_t y2 = y1 + h - 1;
	len = (w >> 3) * h;
	offset = 192 * num;
	end = offset + len;

    //set coloumn address (XS to XE)
    TFT_Write_Cmd(0x2A);
    TFT_Write_Data(x1 >> 8);
    TFT_Write_Data(x1 & 0xFF);
    TFT_Write_Data(x2 >> 8);
    TFT_Write_Data(x2 & 0xFF);
	
	//set row address (YS to YE)
    TFT_Write_Cmd(0x2B);
    TFT_Write_Data(y1 >> 8);
    TFT_Write_Data(y1 & 0xFF);
    TFT_Write_Data(y2 >> 8);
    TFT_Write_Data(y2 & 0xFF);
	
	//memory write command
    TFT_Write_Cmd(0x2C);
	
	TFT_RS_Pin_State_Set(LOGIC_HIGH);
	SPI_Slave_Select();
	
	hi = color >> 8;
    lo = color & 0xFF;
	
	
    //Send the buffer line-by-line
    for (bytes = offset; bytes < end; bytes++)
    {
		//char_val = font32x48[bytes];
        for (bits = 7; bits >= 0; bits--)
        {
			if(char_val & (1 << bits))
			{
				SPI_Transfer(hi);
				SPI_Transfer(lo);
			}
			else
			{
				SPI_Transfer(0x00);
				SPI_Transfer(0x00);
			}
        }
    }
	SPI_Slave_Deselect();
}


void TFT_Print_Integer_Number(int16_t num, uint16_t x, uint16_t y, uint16_t color)
{
	//print from right side
	//decrement x value
	x += 190;
	
	uint8_t  digits[6] = {10,10,10,10,10,10};
	uint8_t  tot_digits = 0, nflag = 0, i, printed_digits = 0;
	int8_t   cnt;
	uint16_t x_offset = 0;
	
	
	
	if(num == 0)
	{
		digits[0] = 0;
		tot_digits = 1;
	}
	else
	{
		i = 0;
		if(num < 0)
		{
			nflag = 1;
			num = -num;
			//digits[i] = 11;
			//i++;
		}
		
		
		
		while(num != 0)
		{
			digits[i] = num % 10;
			num /= 10;
			i++;
		}
		tot_digits = i;
	}
	
	
	
	for(cnt = 0; cnt < tot_digits; cnt++)
	{
		TFT_Print_Number(digits[cnt], x + x_offset, y, 32, 48, color);
		x_offset -= 35;
		printed_digits++;
	}
	
	if(nflag == 1)
	{
		TFT_Print_Number(11, x + x_offset, y, 32, 48, color);
		x_offset -= 35;
		printed_digits++;
	}
	else
	{
		TFT_Print_Number(10, x + x_offset, y, 32, 48, color);
		x_offset -= 35;
		printed_digits++;
	}
	
	for(cnt = printed_digits; cnt <= 5; cnt++)
	{
		TFT_Print_Number(10, x + x_offset, y, 32, 48, color);
		x_offset -= 35;
		printed_digits++;
	}
}


